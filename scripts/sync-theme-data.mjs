/**
 * Copies the canonical tool data into the WordPress theme as plain JS globals.
 * Keeping one source prevents the Astro tools and the WordPress shortcodes from
 * drifting apart, which is the failure mode that makes two implementations of the
 * same tool worse than one.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const emit = (src, global, dest) => {
  const data = JSON.parse(readFileSync(src, 'utf8'));
  writeFileSync(
    dest,
    `/* GENERATED by scripts/sync-theme-data.mjs — do not edit.
   Source of truth: ${src} */
window.${global} = ${JSON.stringify(data, null, 2)};
`,
  );
  return data;
};

const flight = emit(
  'src/data/ballflight.json',
  'GE_BALL_FLIGHT',
  'theme/going-eagle/assets/js/ball-flight-data.js',
);
const budget = emit(
  'src/data/simbudget.json',
  'GE_SIM_BUDGET',
  'theme/going-eagle/assets/js/sim-budget-data.js',
);

console.log(
  `Synced ${Object.keys(flight.FLIGHTS).length} flights and ${flight.STRIKE.length} strike faults, ` +
    `plus ${Object.keys(budget.BUILDS).length} simulator build profiles, to the theme.`,
);
