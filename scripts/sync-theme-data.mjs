/**
 * Copies the canonical ball-flight data into the WordPress theme as a plain JS
 * global. Keeping one source prevents the Astro tool and the WordPress shortcode
 * from drifting apart, which is the failure mode that makes two implementations of
 * the same tool worse than one.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const data = JSON.parse(readFileSync('src/data/ballflight.json', 'utf8'));

const out = `/* GENERATED by scripts/sync-theme-data.mjs — do not edit.
   Source of truth: src/data/ballflight.json */
window.GE_BALL_FLIGHT = ${JSON.stringify(data, null, 2)};
`;

writeFileSync('theme/going-eagle/assets/js/ball-flight-data.js', out);
console.log(
  `Synced ${Object.keys(data.FLIGHTS).length} flights and ${data.STRIKE.length} strike faults to the theme.`,
);
